// Includes for libraries
#include "STM32L432KC_RCC.h"
#include "STM32L432KC_GPIO.h"
#include "STM32L432KC_FLASH.h"
#include "STM32L432KC_TIMER.h"

#define SPEAKER_PIN 6

int main(void) {
    // Configure flash to add waitstates to avoid timing errors
    configureFlash();

    // Setup the PLL and switch clock source to the PLL
    configureClock();

    // Turn on clock to GPIOB
    RCC->AHB2ENR |= (1 << 1);
    
    // Enable TIM6 and TIM7
    configureTimer();

    // Set SPEAKER_PIN as output
    pinMode(SPEAKER_PIN, GPIO_OUTPUT);
    digitalWrite(SPEAKER_PIN, GPIO_LOW);

    int i = 0;

    // Play song until end {0,0}
    while (notes[i][1] != 0) {

        uint32_t frequency = notes[i][0];
        uint32_t duration = notes[i][1];

        // Start timers for the note
        

        //avoid divide by zero errors
        if (frequency != 0) {
          startPitchTimer(frequency);
        }

        startDurationTimer(duration);

        // Play for the duration
        while (!timerDone(TIM7)) {

            // Toggle speaker at the desired frequency
            if (frequency != 0 && timerDone(TIM6)) {
                togglePin(SPEAKER_PIN);
            }
        }

        // Stop timers after note
        stopTimer(TIM6);
        stopTimer(TIM7);

        // Speaker is low between notes
        digitalWrite(SPEAKER_PIN, GPIO_LOW);

        i++;
    }

    // Do nothing once song finishes
    while (1);
   
    return 0;
}
